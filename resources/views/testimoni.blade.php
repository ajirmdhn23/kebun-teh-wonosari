      <p><strong>Sabtu, 21 Juni 2025, di Kebun Teh Lawang, Kabupaten Malang</strong> — Acara “One Day Trip at Wisata Agro Wonosari” mengusung konsep perjalanan santai namun bermakna. Peserta diajak menikmati keindahan kebun teh, tur pabrik pengolahan, hingga kegiatan jeep adventure yang menantang. Kegiatan ditutup dengan piknik sore dan penerbangan lentera harapan, menciptakan suasana hangat dan berkesan.</p>

